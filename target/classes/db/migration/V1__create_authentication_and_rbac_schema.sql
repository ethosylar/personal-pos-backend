-- ============================================================
-- PERSONAL POS
-- Authentication and Role-Based Access Control Schema
-- ============================================================


-- ============================================================
-- STATUS TABLES
-- ============================================================

CREATE TABLE st_user_status_us (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(255),

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_st_user_status_us_code UNIQUE (code)
);


-- ============================================================
-- LOOKUP TABLES
-- ============================================================

CREATE TABLE lt_roles_rl (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(255),

    is_system BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_lt_roles_rl_code UNIQUE (code)
);


CREATE TABLE lt_modules_mod (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(100) NOT NULL,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(255),

    route VARCHAR(255),
    icon VARCHAR(100),

    display_order INTEGER NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_lt_modules_mod_code UNIQUE (code)
);


CREATE TABLE lt_module_permissions_mp (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    module_id BIGINT NOT NULL,

    code VARCHAR(100) NOT NULL,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(255),

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_mp_module
        FOREIGN KEY (module_id)
        REFERENCES lt_modules_mod(id)
        ON DELETE CASCADE,

    CONSTRAINT uk_mp_module_code
        UNIQUE (module_id, code)
);


-- ============================================================
-- DATA TABLES
-- ============================================================

CREATE TABLE dt_users_usr (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    username VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,

    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(150),

    user_status_id BIGINT NOT NULL,

    failed_login_attempts INTEGER NOT NULL DEFAULT 0,

    last_login_at TIMESTAMPTZ,
    password_changed_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_usr_status
        FOREIGN KEY (user_status_id)
        REFERENCES st_user_status_us(id),

    CONSTRAINT uk_dt_users_usr_username
        UNIQUE (username),

    CONSTRAINT uk_dt_users_usr_email
        UNIQUE (email),

    CONSTRAINT chk_usr_failed_login
        CHECK (failed_login_attempts >= 0)
);


CREATE TABLE dt_user_roles_ur (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,

    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    assigned_by BIGINT,

    CONSTRAINT fk_ur_user
        FOREIGN KEY (user_id)
        REFERENCES dt_users_usr(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_ur_role
        FOREIGN KEY (role_id)
        REFERENCES lt_roles_rl(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_ur_assigned_by
        FOREIGN KEY (assigned_by)
        REFERENCES dt_users_usr(id)
        ON DELETE SET NULL,

    CONSTRAINT uk_dt_user_roles_ur
        UNIQUE (user_id, role_id)
);


CREATE TABLE dt_role_modules_rm (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    role_id BIGINT NOT NULL,
    module_id BIGINT NOT NULL,

    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    assigned_by BIGINT,

    CONSTRAINT fk_rm_role
        FOREIGN KEY (role_id)
        REFERENCES lt_roles_rl(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_rm_module
        FOREIGN KEY (module_id)
        REFERENCES lt_modules_mod(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_rm_assigned_by
        FOREIGN KEY (assigned_by)
        REFERENCES dt_users_usr(id)
        ON DELETE SET NULL,

    CONSTRAINT uk_dt_role_modules_rm
        UNIQUE (role_id, module_id)
);


CREATE TABLE dt_role_module_permissions_rmp (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    role_module_id BIGINT NOT NULL,
    module_permission_id BIGINT NOT NULL,

    granted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    granted_by BIGINT,

    CONSTRAINT fk_rmp_role_module
        FOREIGN KEY (role_module_id)
        REFERENCES dt_role_modules_rm(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_rmp_module_permission
        FOREIGN KEY (module_permission_id)
        REFERENCES lt_module_permissions_mp(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_rmp_granted_by
        FOREIGN KEY (granted_by)
        REFERENCES dt_users_usr(id)
        ON DELETE SET NULL,

    CONSTRAINT uk_dt_role_module_permissions_rmp
        UNIQUE (role_module_id, module_permission_id)
);


-- ============================================================
-- INDEXES
-- ============================================================

CREATE INDEX idx_usr_status
    ON dt_users_usr(user_status_id);

CREATE INDEX idx_ur_user
    ON dt_user_roles_ur(user_id);

CREATE INDEX idx_ur_role
    ON dt_user_roles_ur(role_id);

CREATE INDEX idx_mp_module
    ON lt_module_permissions_mp(module_id);

CREATE INDEX idx_rm_role
    ON dt_role_modules_rm(role_id);

CREATE INDEX idx_rm_module
    ON dt_role_modules_rm(module_id);

CREATE INDEX idx_rmp_role_module
    ON dt_role_module_permissions_rmp(role_module_id);

CREATE INDEX idx_rmp_permission
    ON dt_role_module_permissions_rmp(module_permission_id);