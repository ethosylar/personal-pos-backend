-- ============================================================
-- STAFF STATUS
-- ============================================================

CREATE TABLE st_staff_status_sfs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500),

    display_order INTEGER NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_staff_status_code
        UNIQUE (code),

    CONSTRAINT chk_staff_status_display
        CHECK (display_order >= 0)
);


-- ============================================================
-- SALARY / PAY TYPES
-- ============================================================

CREATE TABLE lt_salary_pay_types_spt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500),

    display_order INTEGER NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_salary_pay_type_code
        UNIQUE (code),

    CONSTRAINT chk_salary_pay_type_display
        CHECK (display_order >= 0)
);


-- ============================================================
-- STAFF
-- ============================================================

CREATE TABLE dt_staff_stf (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    staff_code VARCHAR(50) NOT NULL,

    full_name VARCHAR(150) NOT NULL,

    email VARCHAR(150),
    phone VARCHAR(50),

    /*
     * Optional link.
     *
     * A cafe employee does NOT need to be a POS system user.
     */
    user_id BIGINT,

    status_id BIGINT NOT NULL,

    hire_date DATE NOT NULL,

    termination_date DATE,

    notes VARCHAR(1000),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_staff_code
        UNIQUE (staff_code),

    CONSTRAINT fk_staff_user
        FOREIGN KEY (user_id)
        REFERENCES dt_users_usr(id),

    CONSTRAINT fk_staff_status
        FOREIGN KEY (status_id)
        REFERENCES st_staff_status_sfs(id),

    CONSTRAINT chk_staff_dates
        CHECK (
            termination_date IS NULL
            OR termination_date >= hire_date
        )
);


-- Prevent one application user being linked to several staff records.

CREATE UNIQUE INDEX uk_staff_user
    ON dt_staff_stf(user_id)
    WHERE user_id IS NOT NULL;


-- ============================================================
-- STAFF SALARY RATE HISTORY
-- ============================================================

CREATE TABLE dt_staff_salary_rates_ssr (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    staff_id BIGINT NOT NULL,

    pay_type_id BIGINT NOT NULL,

    /*
     * MONTHLY:
     * RM2800 / month
     *
     * DAILY:
     * RM100 / day
     *
     * HOURLY:
     * RM12 / hour
     */
    base_rate NUMERIC(18, 4) NOT NULL,

    /*
     * Recurring allowance associated with this salary rate.
     *
     * Example:
     * transport allowance RM100/month.
     */
    fixed_allowance NUMERIC(18, 4)
        NOT NULL DEFAULT 0,

    currency_code VARCHAR(3)
        NOT NULL DEFAULT 'MYR',

    effective_from DATE NOT NULL,

    /*
     * NULL means this is currently open-ended.
     */
    effective_to DATE,

    notes VARCHAR(1000),

    created_by_user_id BIGINT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_ssr_staff
        FOREIGN KEY (staff_id)
        REFERENCES dt_staff_stf(id),

    CONSTRAINT fk_ssr_pay_type
        FOREIGN KEY (pay_type_id)
        REFERENCES lt_salary_pay_types_spt(id),

    CONSTRAINT fk_ssr_created_by
        FOREIGN KEY (created_by_user_id)
        REFERENCES dt_users_usr(id),

    CONSTRAINT chk_ssr_base_rate
        CHECK (base_rate >= 0),

    CONSTRAINT chk_ssr_allowance
        CHECK (fixed_allowance >= 0),

    CONSTRAINT chk_ssr_effective_dates
        CHECK (
            effective_to IS NULL
            OR effective_to >= effective_from
        )
);


-- Only one open/current salary rate per employee.

CREATE UNIQUE INDEX uk_ssr_current_staff
    ON dt_staff_salary_rates_ssr(staff_id)
    WHERE effective_to IS NULL;


CREATE INDEX idx_staff_status
    ON dt_staff_stf(status_id);

CREATE INDEX idx_staff_hire_date
    ON dt_staff_stf(hire_date);

CREATE INDEX idx_ssr_staff
    ON dt_staff_salary_rates_ssr(staff_id);

CREATE INDEX idx_ssr_effective
    ON dt_staff_salary_rates_ssr(
        effective_from,
        effective_to
    );