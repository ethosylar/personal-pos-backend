-- ============================================================
-- PURCHASE ORDER STATUS
-- ============================================================

CREATE TABLE st_purchase_order_status_pos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500),

    display_order INTEGER NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_purchase_order_status_code
        UNIQUE (code),

    CONSTRAINT chk_purchase_order_status_display
        CHECK (display_order >= 0)
);


-- ============================================================
-- PURCHASE ORDER HEADER
-- ============================================================

CREATE TABLE dt_purchase_orders_po (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    po_number VARCHAR(100) NOT NULL,

    supplier_id BIGINT NOT NULL,
    status_id BIGINT NOT NULL,

    order_date DATE NOT NULL,
    expected_delivery_date DATE,

    subtotal NUMERIC(18, 4) NOT NULL DEFAULT 0,
    tax_amount NUMERIC(18, 4) NOT NULL DEFAULT 0,
    delivery_fee NUMERIC(18, 4) NOT NULL DEFAULT 0,
    total_amount NUMERIC(18, 4) NOT NULL DEFAULT 0,

    notes VARCHAR(1000),

    created_by_user_id BIGINT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_purchase_orders_number
        UNIQUE (po_number),

    CONSTRAINT fk_po_supplier
        FOREIGN KEY (supplier_id)
        REFERENCES dt_suppliers_sup(id),

    CONSTRAINT fk_po_status
        FOREIGN KEY (status_id)
        REFERENCES st_purchase_order_status_pos(id),

    CONSTRAINT fk_po_created_by
        FOREIGN KEY (created_by_user_id)
        REFERENCES dt_users_usr(id),

    CONSTRAINT chk_po_subtotal
        CHECK (subtotal >= 0),

    CONSTRAINT chk_po_tax
        CHECK (tax_amount >= 0),

    CONSTRAINT chk_po_delivery_fee
        CHECK (delivery_fee >= 0),

    CONSTRAINT chk_po_total
        CHECK (total_amount >= 0),

    CONSTRAINT chk_po_delivery_date
        CHECK (
            expected_delivery_date IS NULL
            OR expected_delivery_date >= order_date
        )
);


-- ============================================================
-- PURCHASE ORDER ITEMS
-- ============================================================

CREATE TABLE dt_purchase_order_items_poi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    purchase_order_id BIGINT NOT NULL,
    ingredient_id BIGINT NOT NULL,

    /*
     * Purchase unit snapshot.
     *
     * Example:
     * BAG, BOTTLE, PACK
     */
    purchase_unit_id BIGINT NOT NULL,

    /*
     * Number of purchase units ordered.
     *
     * Example:
     * 2 bags.
     */
    ordered_quantity NUMERIC(18, 4) NOT NULL,

    /*
     * Number of ingredient BASE units contained
     * in ONE purchase unit at the time PO was created.
     *
     * Example:
     * 1 BAG = 1000 G
     */
    base_quantity_per_unit NUMERIC(18, 4) NOT NULL,

    /*
     * Price per PURCHASE unit.
     *
     * Example:
     * RM85 per BAG.
     */
    unit_price NUMERIC(18, 4) NOT NULL,

    line_subtotal NUMERIC(18, 4) NOT NULL,

    supplier_item_code VARCHAR(100),

    notes VARCHAR(1000),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_poi_purchase_order
        FOREIGN KEY (purchase_order_id)
        REFERENCES dt_purchase_orders_po(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_poi_ingredient
        FOREIGN KEY (ingredient_id)
        REFERENCES dt_ingredients_ing(id),

    CONSTRAINT fk_poi_purchase_unit
        FOREIGN KEY (purchase_unit_id)
        REFERENCES lt_units_uom(id),

    CONSTRAINT uk_poi_po_ingredient
        UNIQUE (
            purchase_order_id,
            ingredient_id
        ),

    CONSTRAINT chk_poi_ordered_qty
        CHECK (ordered_quantity > 0),

    CONSTRAINT chk_poi_base_qty
        CHECK (base_quantity_per_unit > 0),

    CONSTRAINT chk_poi_unit_price
        CHECK (unit_price >= 0),

    CONSTRAINT chk_poi_subtotal
        CHECK (line_subtotal >= 0)
);


-- ============================================================
-- GOODS RECEIPT HEADER
-- ============================================================

CREATE TABLE dt_goods_receipts_gr (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    receipt_number VARCHAR(100) NOT NULL,

    purchase_order_id BIGINT NOT NULL,

    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    supplier_delivery_no VARCHAR(100),

    notes VARCHAR(1000),

    received_by_user_id BIGINT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_goods_receipts_number
        UNIQUE (receipt_number),

    CONSTRAINT fk_gr_purchase_order
        FOREIGN KEY (purchase_order_id)
        REFERENCES dt_purchase_orders_po(id),

    CONSTRAINT fk_gr_received_by
        FOREIGN KEY (received_by_user_id)
        REFERENCES dt_users_usr(id)
);


-- ============================================================
-- GOODS RECEIPT ITEMS
-- ============================================================

CREATE TABLE dt_goods_receipt_items_gri (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    goods_receipt_id BIGINT NOT NULL,
    purchase_order_item_id BIGINT NOT NULL,

    /*
     * Number of PURCHASE units actually received.
     *
     * Example:
     * PO = 2 bags
     * first receipt = 1 bag
     */
    received_quantity NUMERIC(18, 4) NOT NULL,

    /*
     * Snapshots copied from the PO item.
     */
    base_quantity_per_unit NUMERIC(18, 4) NOT NULL,
    unit_price NUMERIC(18, 4) NOT NULL,

    /*
     * Total quantity added to inventory in BASE units.
     *
     * received_quantity × base_quantity_per_unit
     */
    received_base_quantity NUMERIC(18, 4) NOT NULL,

    /*
     * Cost per ingredient BASE unit.
     *
     * unit_price ÷ base_quantity_per_unit
     */
    base_unit_cost NUMERIC(18, 6) NOT NULL,

    notes VARCHAR(1000),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_gri_goods_receipt
        FOREIGN KEY (goods_receipt_id)
        REFERENCES dt_goods_receipts_gr(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_gri_po_item
        FOREIGN KEY (purchase_order_item_id)
        REFERENCES dt_purchase_order_items_poi(id),

    CONSTRAINT uk_gri_receipt_po_item
        UNIQUE (
            goods_receipt_id,
            purchase_order_item_id
        ),

    CONSTRAINT chk_gri_received_qty
        CHECK (received_quantity > 0),

    CONSTRAINT chk_gri_base_qty
        CHECK (base_quantity_per_unit > 0),

    CONSTRAINT chk_gri_unit_price
        CHECK (unit_price >= 0),

    CONSTRAINT chk_gri_received_base_qty
        CHECK (received_base_quantity > 0),

    CONSTRAINT chk_gri_base_unit_cost
        CHECK (base_unit_cost >= 0)
);


