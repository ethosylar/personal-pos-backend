-- ============================================================
-- MONTHLY STAFF COST STATUS
-- ============================================================

CREATE TABLE st_staff_monthly_cost_status_smcs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500),

    display_order INTEGER NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_smcs_code
        UNIQUE (code),

    CONSTRAINT chk_smcs_display_order
        CHECK (display_order >= 0)
);


-- ============================================================
-- MONTHLY STAFF COST
-- ============================================================

CREATE TABLE dt_staff_monthly_costs_smc (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    cost_number VARCHAR(100) NOT NULL,

    staff_id BIGINT NOT NULL,

    /*
     * Salary rate used as the source for this payroll record.
     */
    salary_rate_id BIGINT NOT NULL,

    status_id BIGINT NOT NULL,

    period_year SMALLINT NOT NULL,

    period_month SMALLINT NOT NULL,

    /*
     * Salary information is snapshotted because the
     * salary-rate record may no longer be the current rate.
     */
    pay_type_code_snapshot VARCHAR(50) NOT NULL,

    base_rate_snapshot NUMERIC(18, 4) NOT NULL,

    fixed_allowance_snapshot NUMERIC(18, 4)
        NOT NULL DEFAULT 0,

    /*
     * Used for DAILY / HOURLY employees.
     *
     * MONTHLY employees normally leave this NULL.
     */
    units_worked NUMERIC(18, 4),

    /*
     * Calculated base salary actually applicable to the month.
     */
    base_pay NUMERIC(18, 4) NOT NULL,

    additional_allowance NUMERIC(18, 4)
        NOT NULL DEFAULT 0,

    overtime_pay NUMERIC(18, 4)
        NOT NULL DEFAULT 0,

    bonus_amount NUMERIC(18, 4)
        NOT NULL DEFAULT 0,

    /*
     * Employee-side deductions.
     *
     * These affect net pay but NOT employer staff cost.
     */
    deduction_amount NUMERIC(18, 4)
        NOT NULL DEFAULT 0,

    /*
     * Employer-side cost such as employer statutory
     * contributions if you decide to enter them.
     */
    employer_contribution NUMERIC(18, 4)
        NOT NULL DEFAULT 0,

    /*
     * base_pay
     * + fixed allowance
     * + additional allowance
     * + overtime
     * + bonus
     */
    gross_pay NUMERIC(18, 4) NOT NULL,

    /*
     * gross_pay - deduction_amount
     */
    net_pay NUMERIC(18, 4) NOT NULL,

    /*
     * gross_pay + employer_contribution
     *
     * This is what Monthly Accounting will use.
     */
    total_staff_cost NUMERIC(18, 4) NOT NULL,

    notes VARCHAR(1000),

    created_by_user_id BIGINT,

    posted_at TIMESTAMPTZ,
    posted_by_user_id BIGINT,

    voided_at TIMESTAMPTZ,
    voided_by_user_id BIGINT,
    void_reason VARCHAR(500),

    /*
     * TRUE = current valid version for this staff/month.
     *
     * When voided this becomes FALSE, allowing a replacement.
     */
    is_current_record BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_smc_number
        UNIQUE (cost_number),

    CONSTRAINT fk_smc_staff
        FOREIGN KEY (staff_id)
        REFERENCES dt_staff_stf(id),

    CONSTRAINT fk_smc_salary_rate
        FOREIGN KEY (salary_rate_id)
        REFERENCES dt_staff_salary_rates_ssr(id),

    CONSTRAINT fk_smc_status
        FOREIGN KEY (status_id)
        REFERENCES st_staff_monthly_cost_status_smcs(id),

    CONSTRAINT fk_smc_created_by
        FOREIGN KEY (created_by_user_id)
        REFERENCES dt_users_usr(id),

    CONSTRAINT fk_smc_posted_by
        FOREIGN KEY (posted_by_user_id)
        REFERENCES dt_users_usr(id),

    CONSTRAINT fk_smc_voided_by
        FOREIGN KEY (voided_by_user_id)
        REFERENCES dt_users_usr(id),

    CONSTRAINT chk_smc_year
        CHECK (period_year >= 2000),

    CONSTRAINT chk_smc_month
        CHECK (
            period_month >= 1
            AND period_month <= 12
        ),

    CONSTRAINT chk_smc_base_rate
        CHECK (base_rate_snapshot >= 0),

    CONSTRAINT chk_smc_fixed_allowance
        CHECK (fixed_allowance_snapshot >= 0),

    CONSTRAINT chk_smc_units
        CHECK (
            units_worked IS NULL
            OR units_worked > 0
        ),

    CONSTRAINT chk_smc_base_pay
        CHECK (base_pay >= 0),

    CONSTRAINT chk_smc_additional_allowance
        CHECK (additional_allowance >= 0),

    CONSTRAINT chk_smc_overtime
        CHECK (overtime_pay >= 0),

    CONSTRAINT chk_smc_bonus
        CHECK (bonus_amount >= 0),

    CONSTRAINT chk_smc_deduction
        CHECK (deduction_amount >= 0),

    CONSTRAINT chk_smc_employer_contribution
        CHECK (employer_contribution >= 0),

    CONSTRAINT chk_smc_gross
        CHECK (gross_pay >= 0),

    CONSTRAINT chk_smc_net
        CHECK (net_pay >= 0),

    CONSTRAINT chk_smc_total_cost
        CHECK (total_staff_cost >= 0)
);


-- ============================================================
-- ONLY ONE CURRENT RECORD FOR STAFF + MONTH
-- ============================================================

CREATE UNIQUE INDEX uk_smc_current_staff_period
    ON dt_staff_monthly_costs_smc (
        staff_id,
        period_year,
        period_month
    )
    WHERE is_current_record = TRUE;


-- ============================================================
-- NUMBER SEQUENCE
-- ============================================================

CREATE SEQUENCE seq_staff_monthly_cost_number
    START WITH 1
    INCREMENT BY 1;


-- ============================================================
-- INDEXES
-- ============================================================

CREATE INDEX idx_smc_staff
    ON dt_staff_monthly_costs_smc(staff_id);

CREATE INDEX idx_smc_status
    ON dt_staff_monthly_costs_smc(status_id);

CREATE INDEX idx_smc_period
    ON dt_staff_monthly_costs_smc(
        period_year,
        period_month
    );

CREATE INDEX idx_smc_posted_at
    ON dt_staff_monthly_costs_smc(posted_at);