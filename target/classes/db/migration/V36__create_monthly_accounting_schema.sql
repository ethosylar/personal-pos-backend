-- ============================================================
-- MONTHLY ACCOUNTING STATUS
-- ============================================================

CREATE TABLE st_monthly_accounting_status_mas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500),

    display_order INTEGER NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_mas_code
        UNIQUE (code),

    CONSTRAINT chk_mas_display_order
        CHECK (display_order >= 0)
);


-- ============================================================
-- MONTHLY ACCOUNTING
-- ============================================================

CREATE TABLE dt_monthly_accounting_ma (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    accounting_number VARCHAR(100) NOT NULL,

    period_year SMALLINT NOT NULL,
    period_month SMALLINT NOT NULL,

    status_id BIGINT NOT NULL,

    -- ========================================================
    -- SALES
    -- ========================================================

    sales_count INTEGER NOT NULL DEFAULT 0,

    /*
     * Completed sales only.
     *
     * subtotal - sale-level discount
     *
     * Tax is NOT included as revenue.
     */
    net_sales_revenue NUMERIC(18, 4)
        NOT NULL DEFAULT 0,

    tax_collected NUMERIC(18, 4)
        NOT NULL DEFAULT 0,

    /*
     * Sum of completed-sale cost snapshots.
     */
    cogs NUMERIC(18, 6)
        NOT NULL DEFAULT 0,

    /*
     * net_sales_revenue - cogs
     *
     * May legitimately be negative.
     */
    gross_profit NUMERIC(18, 6)
        NOT NULL DEFAULT 0,


    -- ========================================================
    -- OPERATING EXPENSES
    -- ========================================================

    posted_expense_count INTEGER
        NOT NULL DEFAULT 0,

    operating_expenses NUMERIC(18, 4)
        NOT NULL DEFAULT 0,


    -- ========================================================
    -- STAFF COST
    -- ========================================================

    posted_payroll_count INTEGER
        NOT NULL DEFAULT 0,

    staff_cost NUMERIC(18, 4)
        NOT NULL DEFAULT 0,


    -- ========================================================
    -- FINAL OPERATING RESULT
    -- ========================================================

    /*
     * gross_profit
     * - operating_expenses
     * - staff_cost
     *
     * Can be negative.
     */
    operating_profit NUMERIC(18, 6)
        NOT NULL DEFAULT 0,


    -- ========================================================
    -- CONTROL / AUDIT
    -- ========================================================

    notes VARCHAR(1000),

    calculated_at TIMESTAMPTZ NOT NULL,

    calculated_by_user_id BIGINT,

    posted_at TIMESTAMPTZ,

    posted_by_user_id BIGINT,

    voided_at TIMESTAMPTZ,

    voided_by_user_id BIGINT,

    void_reason VARCHAR(500),

    /*
     * Allows a posted statement to be voided while preserving
     * its history and creating a corrected replacement.
     */
    is_current_record BOOLEAN
        NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,


    CONSTRAINT uk_ma_number
        UNIQUE (accounting_number),

    CONSTRAINT fk_ma_status
        FOREIGN KEY (status_id)
        REFERENCES st_monthly_accounting_status_mas(id),

    CONSTRAINT fk_ma_calculated_by
        FOREIGN KEY (calculated_by_user_id)
        REFERENCES dt_users_usr(id),

    CONSTRAINT fk_ma_posted_by
        FOREIGN KEY (posted_by_user_id)
        REFERENCES dt_users_usr(id),

    CONSTRAINT fk_ma_voided_by
        FOREIGN KEY (voided_by_user_id)
        REFERENCES dt_users_usr(id),


    CONSTRAINT chk_ma_year
        CHECK (period_year >= 2000),

    CONSTRAINT chk_ma_month
        CHECK (
            period_month >= 1
            AND period_month <= 12
        ),

    CONSTRAINT chk_ma_sales_count
        CHECK (sales_count >= 0),

    CONSTRAINT chk_ma_net_sales
        CHECK (net_sales_revenue >= 0),

    CONSTRAINT chk_ma_tax
        CHECK (tax_collected >= 0),

    CONSTRAINT chk_ma_cogs
        CHECK (cogs >= 0),

    CONSTRAINT chk_ma_expense_count
        CHECK (posted_expense_count >= 0),

    CONSTRAINT chk_ma_expenses
        CHECK (operating_expenses >= 0),

    CONSTRAINT chk_ma_payroll_count
        CHECK (posted_payroll_count >= 0),

    CONSTRAINT chk_ma_staff_cost
        CHECK (staff_cost >= 0)
);


-- ============================================================
-- ONE CURRENT ACCOUNTING RECORD PER MONTH
-- ============================================================

CREATE UNIQUE INDEX uk_ma_current_period
    ON dt_monthly_accounting_ma (
        period_year,
        period_month
    )
    WHERE is_current_record = TRUE;


-- ============================================================
-- ACCOUNTING NUMBER
-- ============================================================

CREATE SEQUENCE seq_monthly_accounting_number
    START WITH 1
    INCREMENT BY 1;


-- ============================================================
-- INDEXES
-- ============================================================

CREATE INDEX idx_ma_status
    ON dt_monthly_accounting_ma(status_id);

CREATE INDEX idx_ma_period
    ON dt_monthly_accounting_ma(
        period_year,
        period_month
    );

CREATE INDEX idx_ma_posted_at
    ON dt_monthly_accounting_ma(posted_at);

CREATE INDEX idx_ma_calculated_at
    ON dt_monthly_accounting_ma(calculated_at);