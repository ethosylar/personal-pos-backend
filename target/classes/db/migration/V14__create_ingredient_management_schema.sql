-- ============================================================
-- INGREDIENT MASTER
-- ============================================================

CREATE TABLE dt_ingredients_ing (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(50) NOT NULL,
    name VARCHAR(150) NOT NULL,

    ingredient_category_id BIGINT NOT NULL,
    base_unit_id BIGINT NOT NULL,

    minimum_stock_qty NUMERIC(18, 4) NOT NULL DEFAULT 0,
    reorder_qty NUMERIC(18, 4) NOT NULL DEFAULT 0,

    notes VARCHAR(1000),

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_ingredients_ing_code
        UNIQUE (code),

    CONSTRAINT fk_ing_category
        FOREIGN KEY (ingredient_category_id)
        REFERENCES lt_ingredient_categories_ic(id),

    CONSTRAINT fk_ing_base_unit
        FOREIGN KEY (base_unit_id)
        REFERENCES lt_units_uom(id),

    CONSTRAINT chk_ing_minimum_stock
        CHECK (minimum_stock_qty >= 0),

    CONSTRAINT chk_ing_reorder_qty
        CHECK (reorder_qty >= 0)
);


-- ============================================================
-- INGREDIENT SUPPLIER OPTIONS
-- ============================================================

CREATE TABLE dt_ingredient_suppliers_is (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    ingredient_id BIGINT NOT NULL,
    supplier_id BIGINT NOT NULL,

    supplier_item_code VARCHAR(100),

    purchase_unit_id BIGINT NOT NULL,

    /*
     * Number of base units received for one purchased unit.
     *
     * Example:
     * Ingredient base unit = G
     * Supplier purchase unit = BAG
     * One bag contains 1000g
     *
     * base_quantity = 1000
     */
    base_quantity NUMERIC(18, 4) NOT NULL,

    purchase_price NUMERIC(18, 4) NOT NULL,

    is_preferred BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    notes VARCHAR(1000),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_ing_supplier_ingredient
        FOREIGN KEY (ingredient_id)
        REFERENCES dt_ingredients_ing(id),

    CONSTRAINT fk_ing_supplier_supplier
        FOREIGN KEY (supplier_id)
        REFERENCES dt_suppliers_sup(id),

    CONSTRAINT fk_ing_supplier_purchase_unit
        FOREIGN KEY (purchase_unit_id)
        REFERENCES lt_units_uom(id),

    CONSTRAINT uk_ing_supplier
        UNIQUE (ingredient_id, supplier_id),

    CONSTRAINT chk_ing_supplier_base_quantity
        CHECK (base_quantity > 0),

    CONSTRAINT chk_ing_supplier_purchase_price
        CHECK (purchase_price >= 0)
);


-- ============================================================
-- INDEXES
-- ============================================================

CREATE INDEX idx_ing_category
    ON dt_ingredients_ing(ingredient_category_id);

CREATE INDEX idx_ing_base_unit
    ON dt_ingredients_ing(base_unit_id);

CREATE INDEX idx_ing_active
    ON dt_ingredients_ing(is_active);

CREATE INDEX idx_ing_name
    ON dt_ingredients_ing(name);

CREATE INDEX idx_ing_supplier_ingredient
    ON dt_ingredient_suppliers_is(ingredient_id);

CREATE INDEX idx_ing_supplier_supplier
    ON dt_ingredient_suppliers_is(supplier_id);

CREATE INDEX idx_ing_supplier_preferred
    ON dt_ingredient_suppliers_is(
        ingredient_id,
        is_preferred
    );