CREATE TABLE dt_products_prd (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(50) NOT NULL,
    name VARCHAR(150) NOT NULL,

    product_category_id BIGINT NOT NULL,

    sku VARCHAR(100),
    barcode VARCHAR(100),

    description VARCHAR(1000),

    selling_price NUMERIC(18, 4) NOT NULL DEFAULT 0,

    display_order INTEGER NOT NULL DEFAULT 0,

    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_products_prd_code
        UNIQUE (code),

    CONSTRAINT uk_products_prd_sku
        UNIQUE (sku),

    CONSTRAINT uk_products_prd_barcode
        UNIQUE (barcode),

    CONSTRAINT fk_prd_category
        FOREIGN KEY (product_category_id)
        REFERENCES lt_product_categories_pc(id),

    CONSTRAINT chk_prd_selling_price
        CHECK (selling_price >= 0),

    CONSTRAINT chk_prd_display_order
        CHECK (display_order >= 0)
);

CREATE INDEX idx_prd_category
    ON dt_products_prd(product_category_id);

CREATE INDEX idx_prd_active
    ON dt_products_prd(is_active);

CREATE INDEX idx_prd_available
    ON dt_products_prd(is_available);

CREATE INDEX idx_prd_name
    ON dt_products_prd(name);