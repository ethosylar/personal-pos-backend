-- ============================================================
-- SALES HEADER
-- ============================================================

CREATE TABLE dt_sales_sal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    sale_number VARCHAR(100) NOT NULL,

    status_id BIGINT NOT NULL,

    cashier_user_id BIGINT,

    /*
     * NULL while sale is still a draft/cart.
     */
    sold_at TIMESTAMPTZ,

    /*
     * Before sale-level discount and tax.
     */
    subtotal NUMERIC(18, 4) NOT NULL DEFAULT 0,

    /*
     * Sale-wide discount.
     *
     * Item discounts are stored on individual sale lines.
     */
    discount_amount NUMERIC(18, 4) NOT NULL DEFAULT 0,

    tax_amount NUMERIC(18, 4) NOT NULL DEFAULT 0,

    total_amount NUMERIC(18, 4) NOT NULL DEFAULT 0,

    /*
     * Snapshotted when sale is completed.
     */
    total_cost_snapshot NUMERIC(18, 6),

    gross_profit_snapshot NUMERIC(18, 6),

    notes VARCHAR(1000),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_sales_number
        UNIQUE (sale_number),

    CONSTRAINT fk_sal_status
        FOREIGN KEY (status_id)
        REFERENCES st_sale_status_ss(id),

    CONSTRAINT fk_sal_cashier
        FOREIGN KEY (cashier_user_id)
        REFERENCES dt_users_usr(id),

    CONSTRAINT chk_sal_subtotal
        CHECK (subtotal >= 0),

    CONSTRAINT chk_sal_discount
        CHECK (discount_amount >= 0),

    CONSTRAINT chk_sal_tax
        CHECK (tax_amount >= 0),

    CONSTRAINT chk_sal_total
        CHECK (total_amount >= 0),

    CONSTRAINT chk_sal_total_cost
        CHECK (
            total_cost_snapshot IS NULL
            OR total_cost_snapshot >= 0
        )
);


-- ============================================================
-- SALE ITEMS
-- ============================================================

CREATE TABLE dt_sale_items_si (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    sale_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,

    /*
     * Recipe version actually used when the sale completes.
     *
     * NULL while draft if costing has not been finalized.
     */
    recipe_id BIGINT,

    /*
     * Historical snapshots.
     *
     * Product name/price may change later, but an old receipt
     * should remain exactly as it was when sold.
     */
    product_code_snapshot VARCHAR(50) NOT NULL,
    product_name_snapshot VARCHAR(150) NOT NULL,

    recipe_version_no INTEGER,

    quantity NUMERIC(18, 4) NOT NULL,

    unit_price NUMERIC(18, 4) NOT NULL,

    line_subtotal NUMERIC(18, 4) NOT NULL,

    discount_amount NUMERIC(18, 4) NOT NULL DEFAULT 0,

    line_total NUMERIC(18, 4) NOT NULL,

    /*
     * Cost per ONE product portion when sale completes.
     */
    unit_cost_snapshot NUMERIC(18, 6),

    /*
     * unit_cost_snapshot × quantity
     */
    line_cost_snapshot NUMERIC(18, 6),

    gross_profit_snapshot NUMERIC(18, 6),

    notes VARCHAR(1000),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_si_sale
        FOREIGN KEY (sale_id)
        REFERENCES dt_sales_sal(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_si_product
        FOREIGN KEY (product_id)
        REFERENCES dt_products_prd(id),

    CONSTRAINT fk_si_recipe
        FOREIGN KEY (recipe_id)
        REFERENCES dt_recipes_rcp(id),

    CONSTRAINT chk_si_quantity
        CHECK (quantity > 0),

    CONSTRAINT chk_si_unit_price
        CHECK (unit_price >= 0),

    CONSTRAINT chk_si_subtotal
        CHECK (line_subtotal >= 0),

    CONSTRAINT chk_si_discount
        CHECK (discount_amount >= 0),

    CONSTRAINT chk_si_total
        CHECK (line_total >= 0),

    CONSTRAINT chk_si_unit_cost
        CHECK (
            unit_cost_snapshot IS NULL
            OR unit_cost_snapshot >= 0
        ),

    CONSTRAINT chk_si_line_cost
        CHECK (
            line_cost_snapshot IS NULL
            OR line_cost_snapshot >= 0
        )
);


-- ============================================================
-- PAYMENTS
-- ============================================================

CREATE TABLE dt_payments_pay (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    sale_id BIGINT NOT NULL,

    payment_method_id BIGINT NOT NULL,
    payment_status_id BIGINT NOT NULL,

    amount NUMERIC(18, 4) NOT NULL,

    /*
     * Useful for cash:
     *
     * Total = RM13
     * Customer gives RM20
     * tendered_amount = 20
     * change_amount   = 7
     */
    tendered_amount NUMERIC(18, 4),

    change_amount NUMERIC(18, 4),

    /*
     * Card approval / QR transaction reference etc.
     */
    reference_no VARCHAR(150),

    paid_at TIMESTAMPTZ,

    notes VARCHAR(1000),

    created_by_user_id BIGINT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_pay_sale
        FOREIGN KEY (sale_id)
        REFERENCES dt_sales_sal(id),

    CONSTRAINT fk_pay_method
        FOREIGN KEY (payment_method_id)
        REFERENCES lt_payment_methods_pm(id),

    CONSTRAINT fk_pay_status
        FOREIGN KEY (payment_status_id)
        REFERENCES st_payment_status_ps(id),

    CONSTRAINT fk_pay_created_by
        FOREIGN KEY (created_by_user_id)
        REFERENCES dt_users_usr(id),

    CONSTRAINT chk_pay_amount
        CHECK (amount > 0),

    CONSTRAINT chk_pay_tendered
        CHECK (
            tendered_amount IS NULL
            OR tendered_amount >= 0
        ),

    CONSTRAINT chk_pay_change
        CHECK (
            change_amount IS NULL
            OR change_amount >= 0
        )
);


