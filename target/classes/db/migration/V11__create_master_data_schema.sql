-- ============================================================
-- SUPPLIERS
-- ============================================================

CREATE TABLE dt_suppliers_sup (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(50) NOT NULL,
    name VARCHAR(150) NOT NULL,

    contact_person VARCHAR(150),
    phone VARCHAR(50),
    email VARCHAR(150),

    address_line_1 VARCHAR(255),
    address_line_2 VARCHAR(255),

    city VARCHAR(100),
    state VARCHAR(100),
    postcode VARCHAR(30),
    country VARCHAR(100),

    registration_no VARCHAR(100),
    tax_registration_no VARCHAR(100),

    payment_terms_days INTEGER NOT NULL DEFAULT 0,

    notes VARCHAR(1000),

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_suppliers_sup_code
        UNIQUE (code),

    CONSTRAINT chk_suppliers_sup_payment_terms
        CHECK (payment_terms_days >= 0)
);


-- ============================================================
-- INDEXES
-- ============================================================

CREATE INDEX idx_product_categories_active
    ON lt_product_categories_pc(
        is_active,
        display_order
    );

CREATE INDEX idx_ingredient_categories_active
    ON lt_ingredient_categories_ic(
        is_active,
        display_order
    );

CREATE INDEX idx_suppliers_active
    ON dt_suppliers_sup(is_active);

CREATE INDEX idx_suppliers_name
    ON dt_suppliers_sup(name);