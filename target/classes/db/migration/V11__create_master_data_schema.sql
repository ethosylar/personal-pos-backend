-- ============================================================
-- UNITS OF MEASURE
-- ============================================================

CREATE TABLE lt_units_uom (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(30) NOT NULL,
    name VARCHAR(100) NOT NULL,
    symbol VARCHAR(20),

    measurement_type VARCHAR(30) NOT NULL,

    is_base_unit BOOLEAN NOT NULL DEFAULT FALSE,

    display_order INTEGER NOT NULL DEFAULT 0,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_units_uom_code
        UNIQUE (code),

    CONSTRAINT chk_units_uom_measurement_type
        CHECK (
            measurement_type IN (
                'MASS',
                'VOLUME',
                'COUNT',
                'PACKAGE'
            )
        ),

    CONSTRAINT chk_units_uom_display_order
        CHECK (display_order >= 0)
);


-- ============================================================
-- PRODUCT CATEGORIES
-- ============================================================

CREATE TABLE lt_product_categories_pc (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500),

    display_order INTEGER NOT NULL DEFAULT 0,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_product_categories_pc_code
        UNIQUE (code),

    CONSTRAINT chk_product_categories_pc_display_order
        CHECK (display_order >= 0)
);


-- ============================================================
-- INGREDIENT CATEGORIES
-- ============================================================

CREATE TABLE lt_ingredient_categories_ic (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500),

    display_order INTEGER NOT NULL DEFAULT 0,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_ingredient_categories_ic_code
        UNIQUE (code),

    CONSTRAINT chk_ingredient_categories_ic_display_order
        CHECK (display_order >= 0)
