-- ============================================================
-- EXPENSE CATEGORIES
-- ============================================================

CREATE TABLE lt_expense_categories_ec (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500),

    /*
     * FIXED
     * VARIABLE
     * OTHER
     */
    expense_class VARCHAR(30) NOT NULL DEFAULT 'OTHER',

    display_order INTEGER NOT NULL DEFAULT 0,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_expense_categories_code
        UNIQUE (code),

    CONSTRAINT chk_expense_category_class
        CHECK (
            expense_class IN (
                'FIXED',
                'VARIABLE',
                'OTHER'
            )
        ),

    CONSTRAINT chk_expense_category_display
        CHECK (display_order >= 0)
);


-- ============================================================
-- EXPENSE STATUS
-- ============================================================

CREATE TABLE st_expense_status_es (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500),

    display_order INTEGER NOT NULL DEFAULT 0,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_expense_status_code
        UNIQUE (code),

    CONSTRAINT chk_expense_status_display
        CHECK (display_order >= 0)
);


-- ============================================================
-- EXPENSES
-- ============================================================

CREATE TABLE dt_expenses_exp (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    expense_number VARCHAR(100) NOT NULL,

    category_id BIGINT NOT NULL,
    status_id BIGINT NOT NULL,

    /*
     * Optional because some expenses may be paid to parties
     * that are not configured as procurement suppliers.
     */
    supplier_id BIGINT,

    expense_date DATE NOT NULL,

    description VARCHAR(500) NOT NULL,

    /*
     * Amount excluding tax.
     */
    amount NUMERIC(18, 4) NOT NULL,

    tax_amount NUMERIC(18, 4) NOT NULL DEFAULT 0,

    /*
     * amount + tax_amount
     */
    total_amount NUMERIC(18, 4) NOT NULL,

    /*
     * Free-text payee for utility company,
     * landlord, software vendor, etc.
     */
    payee_name VARCHAR(150),

    /*
     * Invoice / bill / receipt reference.
     */
    reference_no VARCHAR(150),

    notes VARCHAR(1000),

    created_by_user_id BIGINT,

    posted_at TIMESTAMPTZ,

    posted_by_user_id BIGINT,

    voided_at TIMESTAMPTZ,

    voided_by_user_id BIGINT,

    void_reason VARCHAR(500),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_expenses_number
        UNIQUE (expense_number),

    CONSTRAINT fk_exp_category
        FOREIGN KEY (category_id)
        REFERENCES lt_expense_categories_ec(id),

    CONSTRAINT fk_exp_status
        FOREIGN KEY (status_id)
        REFERENCES st_expense_status_es(id),

    CONSTRAINT fk_exp_supplier
        FOREIGN KEY (supplier_id)
        REFERENCES dt_suppliers_sup(id),

    CONSTRAINT fk_exp_created_by
        FOREIGN KEY (created_by_user_id)
        REFERENCES dt_users_usr(id),

    CONSTRAINT fk_exp_posted_by
        FOREIGN KEY (posted_by_user_id)
        REFERENCES dt_users_usr(id),

    CONSTRAINT fk_exp_voided_by
        FOREIGN KEY (voided_by_user_id)
        REFERENCES dt_users_usr(id),

    CONSTRAINT chk_exp_amount
        CHECK (amount >= 0),

    CONSTRAINT chk_exp_tax_amount
        CHECK (tax_amount >= 0),

    CONSTRAINT chk_exp_total_amount
        CHECK (total_amount >= 0)
);


-- ============================================================
-- EXPENSE NUMBER SEQUENCE
-- ============================================================

CREATE SEQUENCE seq_expense_number
    START WITH 1
    INCREMENT BY 1;


-- ============================================================
-- INDEXES
-- ============================================================

CREATE INDEX idx_exp_category
    ON dt_expenses_exp(category_id);

CREATE INDEX idx_exp_status
    ON dt_expenses_exp(status_id);

CREATE INDEX idx_exp_supplier
    ON dt_expenses_exp(supplier_id);

CREATE INDEX idx_exp_date
    ON dt_expenses_exp(expense_date);

CREATE INDEX idx_exp_created_by
    ON dt_expenses_exp(created_by_user_id);

CREATE INDEX idx_exp_posted_at
    ON dt_expenses_exp(posted_at);