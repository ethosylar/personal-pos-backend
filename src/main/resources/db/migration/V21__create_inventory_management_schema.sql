-- ============================================================
-- INVENTORY MOVEMENT TYPES
-- ============================================================

CREATE TABLE lt_inventory_movement_types_imt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500),

    /*
     * +1 = stock enters inventory
     * -1 = stock leaves inventory
     */
    direction SMALLINT NOT NULL,

    /*
     * TRUE means a user is allowed to manually create
     * this type of movement.
     *
     * SALE_USAGE will eventually be generated
     * automatically by the POS.
     */
    is_manual_allowed BOOLEAN NOT NULL DEFAULT TRUE,

    display_order INTEGER NOT NULL DEFAULT 0,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_inventory_movement_types_code
        UNIQUE (code),

    CONSTRAINT chk_inventory_movement_direction
        CHECK (direction IN (-1, 1)),

    CONSTRAINT chk_inventory_movement_display_order
        CHECK (display_order >= 0)
);


-- ============================================================
-- INVENTORY MOVEMENT LEDGER
-- ============================================================

CREATE TABLE dt_inventory_movements_im (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    ingredient_id BIGINT NOT NULL,

    movement_type_id BIGINT NOT NULL,

    /*
     * Quantity is ALWAYS positive.
     *
     * Whether it adds or subtracts stock is determined by
     * lt_inventory_movement_types_imt.direction.
     *
     * Quantity is also ALWAYS expressed using the
     * ingredient's base unit.
     */
    quantity NUMERIC(18, 4) NOT NULL,

    /*
     * Cost per ingredient base unit when this movement
     * happened.
     *
     * Examples:
     *
     * Beans = RM0.085 / g
     * Milk  = RM0.0075 / ml
     *
     * Nullable because some adjustments may not initially
     * have a cost.
     */
    unit_cost NUMERIC(18, 6),

    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    /*
     * Future integration references.
     *
     * Examples:
     *
     * GOODS_RECEIPT
     * SALE
     * SALE_ITEM
     * MANUAL
     * STOCKTAKE
     */
    reference_type VARCHAR(50),

    reference_id BIGINT,

    reference_no VARCHAR(100),

    reason VARCHAR(500),

    notes VARCHAR(1000),

    created_by_user_id BIGINT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_im_ingredient
        FOREIGN KEY (ingredient_id)
        REFERENCES dt_ingredients_ing(id),

    CONSTRAINT fk_im_movement_type
        FOREIGN KEY (movement_type_id)
        REFERENCES lt_inventory_movement_types_imt(id),

    CONSTRAINT fk_im_created_by
        FOREIGN KEY (created_by_user_id)
        REFERENCES dt_users_usr(id),

    CONSTRAINT chk_im_quantity
        CHECK (quantity > 0),

    CONSTRAINT chk_im_unit_cost
        CHECK (
            unit_cost IS NULL
            OR unit_cost >= 0
        )
);


-- ============================================================
-- INDEXES
-- ============================================================

CREATE INDEX idx_im_ingredient
    ON dt_inventory_movements_im(ingredient_id);

CREATE INDEX idx_im_movement_type
    ON dt_inventory_movements_im(movement_type_id);

CREATE INDEX idx_im_occurred_at
    ON dt_inventory_movements_im(occurred_at);

CREATE INDEX idx_im_ingredient_occurred
    ON dt_inventory_movements_im(
        ingredient_id,
        occurred_at DESC
    );

CREATE INDEX idx_im_reference
    ON dt_inventory_movements_im(
        reference_type,
        reference_id
    );

CREATE INDEX idx_im_created_by
    ON dt_inventory_movements_im(created_by_user_id);