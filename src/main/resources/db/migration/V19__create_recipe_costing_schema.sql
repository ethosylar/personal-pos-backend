-- ============================================================
-- RECIPE VERSION
-- ============================================================

CREATE TABLE dt_recipes_rcp (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    product_id BIGINT NOT NULL,

    version_no INTEGER NOT NULL,

    /*
     * Number of product portions produced by this recipe.
     *
     * Example:
     * Iced Latte recipe = 1 serving
     * Batch cold brew = 10 servings
     */
    yield_quantity NUMERIC(18, 4) NOT NULL DEFAULT 1,

    effective_from TIMESTAMPTZ,
    effective_to TIMESTAMPTZ,

    /*
     * Only one recipe version may be current for a product.
     *
     * Draft:
     * is_current = FALSE
     * effective_from = NULL
     *
     * Current:
     * is_current = TRUE
     *
     * Retired:
     * is_current = FALSE
     * effective_to != NULL
     */
    is_current BOOLEAN NOT NULL DEFAULT FALSE,

    /*
     * Cost per product portion when this version
     * was activated.
     *
     * Live/current costing will still be calculated
     * dynamically from ingredient supplier costs.
     */
    activated_cost_snapshot NUMERIC(18, 6),

    activated_at TIMESTAMPTZ,

    notes VARCHAR(1000),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_rcp_product
        FOREIGN KEY (product_id)
        REFERENCES dt_products_prd(id),

    CONSTRAINT uk_rcp_product_version
        UNIQUE (product_id, version_no),

    CONSTRAINT chk_rcp_version
        CHECK (version_no > 0),

    CONSTRAINT chk_rcp_yield
        CHECK (yield_quantity > 0),

    CONSTRAINT chk_rcp_effective_dates
        CHECK (
            effective_to IS NULL
            OR effective_from IS NULL
            OR effective_to >= effective_from
        )
);


-- ============================================================
-- ONLY ONE CURRENT RECIPE PER PRODUCT
-- ============================================================

CREATE UNIQUE INDEX uk_rcp_one_current_per_product
    ON dt_recipes_rcp(product_id)
    WHERE is_current = TRUE;


-- ============================================================
-- RECIPE ITEMS
-- ============================================================

CREATE TABLE dt_recipe_items_ri (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    recipe_id BIGINT NOT NULL,
    ingredient_id BIGINT NOT NULL,

    /*
     * Quantity is always stored in the ingredient's
     * BASE inventory unit.
     *
     * Coffee Beans -> G
     * Milk         -> ML
     * Cup          -> PCS
     */
    quantity NUMERIC(18, 4) NOT NULL,

    /*
     * Example:
     * quantity = 100g
     * waste_percent = 5
     *
     * Costed quantity = 105g
     */
    waste_percent NUMERIC(8, 4) NOT NULL DEFAULT 0,

    display_order INTEGER NOT NULL DEFAULT 0,

    /*
     * Historical cost at the moment this recipe
     * version was activated.
     */
    unit_cost_snapshot NUMERIC(18, 6),
    line_cost_snapshot NUMERIC(18, 6),

    notes VARCHAR(1000),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_ri_recipe
        FOREIGN KEY (recipe_id)
        REFERENCES dt_recipes_rcp(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_ri_ingredient
        FOREIGN KEY (ingredient_id)
        REFERENCES dt_ingredients_ing(id),

    CONSTRAINT uk_ri_recipe_ingredient
        UNIQUE (recipe_id, ingredient_id),

    CONSTRAINT chk_ri_quantity
        CHECK (quantity > 0),

    CONSTRAINT chk_ri_waste
        CHECK (
            waste_percent >= 0
            AND waste_percent <= 100
        ),

    CONSTRAINT chk_ri_display_order
        CHECK (display_order >= 0)
);


-- ============================================================
-- INDEXES
-- ============================================================

CREATE INDEX idx_rcp_product
    ON dt_recipes_rcp(product_id);

CREATE INDEX idx_rcp_current
    ON dt_recipes_rcp(
        product_id,
        is_current
    );

CREATE INDEX idx_ri_recipe
    ON dt_recipe_items_ri(recipe_id);

CREATE INDEX idx_ri_ingredient
    ON dt_recipe_items_ri(ingredient_id);