-- ============================================================
-- INVENTORY STOCK POLICY
-- ============================================================

CREATE TABLE dt_inventory_stock_policies_isp (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    ingredient_id BIGINT NOT NULL,

    /*
     * Ingredient base-unit quantity at which the system
     * should raise a low-stock alert.
     *
     * Examples:
     * Coffee beans = grams
     * Milk         = millilitres
     */
    reorder_level NUMERIC(18, 4)
        NOT NULL DEFAULT 0,

    /*
     * Preferred stock quantity after replenishment.
     *
     * Used to calculate:
     *
     * suggested_reorder =
     * target_stock_level - current_stock
     */
    target_stock_level NUMERIC(18, 4),

    alert_enabled BOOLEAN
        NOT NULL DEFAULT TRUE,

    notes VARCHAR(1000),

    created_at TIMESTAMPTZ
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMPTZ
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_isp_ingredient
        UNIQUE (ingredient_id),

    CONSTRAINT fk_isp_ingredient
        FOREIGN KEY (ingredient_id)
        REFERENCES dt_ingredients_ing(id),

    CONSTRAINT chk_isp_reorder_level
        CHECK (reorder_level >= 0),

    CONSTRAINT chk_isp_target_level
        CHECK (
            target_stock_level IS NULL
            OR target_stock_level >= 0
        ),

    /*
     * If target is configured it should normally be
     * greater than or equal to the reorder threshold.
     */
    CONSTRAINT chk_isp_target_vs_reorder
        CHECK (
            target_stock_level IS NULL
            OR target_stock_level >= reorder_level
        )
);


CREATE INDEX idx_isp_alert_enabled
    ON dt_inventory_stock_policies_isp(
        alert_enabled
    );