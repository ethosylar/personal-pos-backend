-- ============================================================
-- PERSONAL POS
-- Audit Logging Schema
-- ============================================================


-- ============================================================
-- LOOKUP TABLE
-- ============================================================

CREATE TABLE lt_audit_actions_aa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(100) NOT NULL,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(500),

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_lt_audit_actions_aa_code
        UNIQUE (code)
);


-- ============================================================
-- DATA TABLE
-- ============================================================

CREATE TABLE dt_audit_logs_al (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT,

    action_id BIGINT NOT NULL,

    module_id BIGINT,

    entity_type VARCHAR(100) NOT NULL,

    entity_id BIGINT,

    description VARCHAR(1000),

    before_data JSONB,

    after_data JSONB,

    ip_address VARCHAR(45),

    user_agent VARCHAR(500),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_al_user
        FOREIGN KEY (user_id)
        REFERENCES dt_users_usr(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_al_action
        FOREIGN KEY (action_id)
        REFERENCES lt_audit_actions_aa(id),

    CONSTRAINT fk_al_module
        FOREIGN KEY (module_id)
        REFERENCES lt_modules_mod(id)
        ON DELETE SET NULL
);


-- ============================================================
-- INDEXES
-- ============================================================

CREATE INDEX idx_al_user
    ON dt_audit_logs_al(user_id);

CREATE INDEX idx_al_action
    ON dt_audit_logs_al(action_id);

CREATE INDEX idx_al_module
    ON dt_audit_logs_al(module_id);

CREATE INDEX idx_al_entity
    ON dt_audit_logs_al(entity_type, entity_id);

CREATE INDEX idx_al_created_at
    ON dt_audit_logs_al(created_at DESC);